export function getCuratedAssociations(item) {
  if (PRIORITY_CURATED_ASSOCIATIONS[item.num]) {
    return PRIORITY_CURATED_ASSOCIATIONS[item.num];
  }
  // Otherwise, take existing associations, prune filler words, cap at 3-4 words
  const raw = item.everyday_associations || [];
  const filtered = raw
    .map(w => w.trim())
    .filter(w => w.length > 1 && !w.includes(' '))
    .slice(0, 4); // Take max 4 words
  
  if (filtered.length >= 2) return filtered;
  
  // Fallback defaults based on clean name
  return [item.name_he.split(' ')[0], 'סמל'];
}
