// פונקציית העשרה אוטומטית לכל שאר הפריטים (שמות עצם נרדפים, קטגוריות ומונחים ישירים)
function enrichItemBranches(item) {
  // אם יש הגדרה מפורשת במילון המופת - משתמשים בה!
  if (MASTER_BRANCH_DEFINITIONS[item.num]) {
    return MASTER_BRANCH_DEFINITIONS[item.num];
  }

  const name = item.name_he || item.name || '';
  const tokens = name.split(/[\s,.;:!?\-–—/()"]+/).filter(t => t.length >= 2);
  const branches = new Set();

  // הוספת השם השלם והמילים הראשיות
  branches.add(name);
  tokens.forEach(t => branches.add(t));

  // עוגנים לפי שמות מפתח ספציפיים
  const lowerName = name.toLowerCase();
  
  if (lowerName.includes('תנור') || lowerName.includes('אפייה')) {
    ['חום', 'אפייה', 'בישול', 'מטבח', 'פיצה', 'לחם', 'עוגה'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('שמש') || lowerName.includes('חמנייה')) {
    ['חום', 'אור', 'קיץ', 'שמש', 'קרניים', 'צהוב', 'חוף'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('מדבר') || lowerName.includes('חול')) {
    ['חום', 'מדבר', 'חול', 'שמש', 'צמא', 'יובש'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('אש') || lowerName.includes('להבה') || lowerName.includes('מדורה') || lowerName.includes('גפרור') || lowerName.includes('מצית')) {
    ['חום', 'אש', 'להבה', 'הדלקה', 'עשן', 'גחלים'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('קרח') || lowerName.includes('שלג') || lowerName.includes('חורף') || lowerName.includes('איגלו') || lowerName.includes('סקי')) {
    ['קור', 'קרח', 'שלג', 'חורף', 'קפוא'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('רופא') || lowerName.includes('מרפאה') || lowerName.includes('תרופה') || lowerName.includes('חולים')) {
    ['רופא', 'מרפאה', 'בריאות', 'בדיקה', 'מחלה', 'טיפול'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('מכונית') || lowerName.includes('רכב') || lowerName.includes('אוטו') || lowerName.includes('מונית') || lowerName.includes('אוטובוס')) {
    ['נסיעה', 'רכב', 'כביש', 'נהיגה', 'תחבורה'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('מטוס') || lowerName.includes('טיסה') || lowerName.includes('הליקופטר')) {
    ['טיסה', 'מטוס', 'שדה תעופה', 'שמיים', 'חופשה', 'נסיעה'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('אנימה') || lowerName.includes('פוקימון') || lowerName.includes('מנגה') || lowerName.includes('פיקאצ') || lowerName.includes('נארוטו') || lowerName.includes('גוקו')) {
    ['אנימה', 'יפן', 'מנגה', 'גיימינג', 'קוספליי'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('כדורגל') || lowerName.includes('מסי') || lowerName.includes('רונאלדו') || lowerName.includes('שער') || lowerName.includes('גול')) {
    ['כדורגל', 'ספורט', 'משחק', 'גול', 'אצטדיון', 'אימון'].forEach(b => branches.add(b));
  }
  if (lowerName.includes('מחשב') || lowerName.includes('מקלדת') || lowerName.includes('עכבר מחשב') || lowerName.includes('מסך')) {
    ['מחשב', 'טכנולוגיה', 'הייטק', 'מסך', 'עבודה', 'מקלדת'].forEach(b => branches.add(b));
  }

  // שמירה על האסוציאציות הקיימות אם אינן סותרות
  if (Array.isArray(item.associations)) {
    item.associations.forEach(a => {
      const cleanA = String(a).trim();
      // סינון אסוציאציות סותרות ידועות
      if (cleanA === 'חום' && (lowerName.includes('מניפה') || lowerName.includes('גלידה') || lowerName.includes('קרח'))) {
        return; // דילוג!
      }
      if (cleanA.length >= 2) {
        branches.add(cleanA);
      }
    });
  }

  return Array.from(branches).slice(0, 10);
}

console.log(`Starting Master Calibration for ${STAGED_IMAGES_POOL.length} items...`);

let masterCount = 0;
let genericCount = 0;

const calibratedPool = STAGED_IMAGES_POOL.map(item => {
  const isMaster = !!MASTER_BRANCH_DEFINITIONS[item.num];
  if (isMaster) masterCount++;
  else genericCount++;

  const cleanBranches = enrichItemBranches(item);

  return {
    ...item,
    associations: cleanBranches,
    everyday_associations: cleanBranches
  };
});

console.log(`Calibrated ${masterCount} master items and ${genericCount} enriched items.`);

