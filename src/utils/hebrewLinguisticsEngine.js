/**
 * בדיקה האם שתי מילים הן שוות-ערך לשונית ובטוחה
 */
export function areHebrewWordsLinguisticallyLinked(word1 = '', word2 = '') {
  if (!word1 || !word2) return false;
  const w1 = stripHebrewPrefixes(word1);
  const w2 = stripHebrewPrefixes(word2);
  if (w1 === w2) return true;

  // בדיקת משפחה מורפולוגית
  const fam1 = getSafeMorphologicalFamily(w1);
  if (fam1.includes(w2)) return true;

  // בדיקת מילה נרדפת קונקרטית בטוחה
  const syns1 = SAFE_CONCRETE_SYNONYMS[w1] || [];
  if (syns1.includes(w2)) return true;

  return false;
}

