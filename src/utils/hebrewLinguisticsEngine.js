// נרמול מילה עברית בצורה נקייה ובטוחה (ללא חיתוך אותיות או גזירת שורשים!)
export function normalizeHebrewWord(word = '') {
  return String(word).trim().toLowerCase().replace(/[^\u0590-\u05FF]/g, '');
}

// שמירה מלאה על שלמות המילה העברית — איסור מוחלט על חיתוך אותיות שמשחית מילים כמו "הילה" או "כדור"
export function stripHebrewPrefixes(word = '') {
  return normalizeHebrewWord(word);
}

