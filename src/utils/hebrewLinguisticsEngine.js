/**
 * חילוץ המשפחה המורפולוגית הבטוחה של מילה
 */
export function getSafeMorphologicalFamily(word = '') {
  const clean = stripHebrewPrefixes(word);
  if (!clean) return [];

  // 1. בדיקה אם המילה היא מפתח מוגדר
  if (SAFE_HEBREW_MORPHOLOGICAL_FAMILIES[clean]) {
    return SAFE_HEBREW_MORPHOLOGICAL_FAMILIES[clean];
  }

  // 2. בדיקה אם המילה כלולה באחת המשפחות
  for (const [rootKey, family] of Object.entries(SAFE_HEBREW_MORPHOLOGICAL_FAMILIES)) {
    if (family.includes(clean) || family.some(f => f === word.trim())) {
      return family;
    }
  }

  return [clean];
}

