/**
 * Returns intuitive essence bridge keywords for a given input word or phrase.
 */
export function getAssociativeLeapBridges(input = '') {
  if (!input) return [];
  const clean = String(input).trim().toLowerCase();
  
  // 1. Direct dictionary match
  if (ESSENCE_LEAP_BRIDGES[clean]) {
    return [...ESSENCE_LEAP_BRIDGES[clean]];
  }

  // 2. Multi-token decomposition (e.g. "לקנות בשר אדום", "להאכיל את הצב", "לתקן את המזגן")
  const tokens = clean.split(/[,\s+./\-]+/).filter(w => w.length > 1);
  const bridges = [];
  for (const token of tokens) {
    if (ESSENCE_LEAP_BRIDGES[token]) {
      for (const b of ESSENCE_LEAP_BRIDGES[token]) {
        if (!bridges.includes(b)) bridges.push(b);
      }
    }
  }

  return bridges;
}
